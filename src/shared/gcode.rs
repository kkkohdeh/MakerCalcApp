use serde::Serialize;

const HEADER_LINE_LIMIT: usize = 2_048;
const RAW_HEADER_LIMIT: usize = 64;
const HEADER_VALUE_LIMIT: usize = 256;
const VARIABLE_KEY_LIMIT: usize = 64;
const UNBROKEN_VALUE_LIMIT: usize = 128;

/// Facts extracted from a slicer's comment header without interpreting G-code commands.
#[derive(Clone, Debug, Default, PartialEq, Serialize)]
pub(crate) struct GcodeFacts {
    pub(crate) slicer: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) slicer_version: Option<String>,
    pub(crate) filament: GcodeFilament,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub(crate) material_channels: Vec<GcodeMaterialChannel>,
    pub(crate) print: GcodePrintProfile,
    /// Local diagnostics are not part of the normalized file contract.
    #[serde(skip)]
    raw_headers: Vec<GcodeHeader>,
}

/// A logical material referenced by a file, before it is routed to a physical supply.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub(crate) struct GcodeMaterialChannel {
    pub(crate) id: u32,
    pub(crate) material: Option<String>,
    pub(crate) color: Option<String>,
    pub(crate) weight_g: Option<f64>,
}

impl GcodeFacts {
    /// The presentation model never retains unclassified source variables.
    pub(crate) fn without_diagnostics(mut self) -> Self {
        self.raw_headers.clear();
        self
    }
}

/// Material attributes for matching a MakerCalc material record.
#[derive(Clone, Debug, Default, PartialEq, Serialize)]
pub(crate) struct GcodeFilament {
    pub(crate) material: Option<String>,
    pub(crate) profile_name: Option<String>,
    pub(crate) length_mm: Option<f64>,
    pub(crate) weight_g: Option<f64>,
    pub(crate) diameter_mm: Option<f64>,
    pub(crate) density_g_cm3: Option<f64>,
}

/// Slicer parameters reported before sending a job.
#[derive(Clone, Debug, Default, PartialEq, Serialize)]
pub(crate) struct GcodePrintProfile {
    #[serde(rename = "estimated_duration_s")]
    pub(crate) estimated_seconds: Option<f64>,
    pub(crate) layer_height_mm: Option<f64>,
    pub(crate) total_layers: Option<u32>,
    pub(crate) max_z_height_mm: Option<f64>,
    pub(crate) nozzle_temperature_c: Option<f64>,
    pub(crate) bed_temperature_c: Option<f64>,
    /// Planned slicer values, never proof of installed hardware or live temperatures.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) nozzle_diameter_mm: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) first_layer_height_mm: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) chamber_temperature_c: Option<f64>,
}

/// A direct comment-header value that does not need a dedicated application field yet.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub(crate) struct GcodeHeader {
    pub(crate) key: String,
    pub(crate) value: String,
}

/// Inspect only `;` slicer header comments; stop at the first command.
/// This keeps results portable across file providers.
pub(crate) fn inspect_gcode_header(content: &str) -> GcodeFacts {
    let mut facts = GcodeFacts::default();
    let mut inside_thumbnail = false;

    for line in content.lines().take(HEADER_LINE_LIMIT) {
        let trimmed = line.trim().trim_start_matches('\u{feff}');
        let Some(comment) = trimmed.strip_prefix(';') else {
            if trimmed.is_empty() {
                continue;
            }
            break;
        };
        let comment = comment.trim();

        if thumbnail_starts(comment) {
            inside_thumbnail = true;
            continue;
        }
        if inside_thumbnail {
            if thumbnail_ends(comment) {
                inside_thumbnail = false;
            }
            continue;
        }
        if let Some(slicer) = comment.strip_prefix("generated by ") {
            set_first_text(&mut facts.slicer, slicer);
            push_raw_header(&mut facts, "generated_by", slicer);
            continue;
        }
        let Some((key, value)) = comment_header_pair(comment) else {
            continue;
        };
        let normalized_key = normalize_header_key(key);
        if !is_slicer_variable(key, &normalized_key, value) {
            continue;
        }
        apply_known_header(&mut facts, &normalized_key, value);
        push_raw_header(&mut facts, &normalized_key, value);
    }

    facts
}

/// Inspect the bounded file head and optional tail.
/// Slicers may put machine settings first and print totals last.
pub(crate) fn inspect_gcode_file_parts(head: &str, tail: Option<&str>) -> GcodeFacts {
    let mut facts = inspect_gcode_header(head);
    let footer = inspect_gcode_footer(tail.unwrap_or(head));
    fill_missing(&mut facts, footer);
    facts
}

fn inspect_gcode_footer(content: &str) -> GcodeFacts {
    let mut facts = GcodeFacts::default();
    for line in content.lines().rev().take(HEADER_LINE_LIMIT) {
        let trimmed = line.trim().trim_start_matches('\u{feff}');
        let Some(comment) = trimmed.strip_prefix(';') else {
            continue;
        };
        let comment = comment.trim();
        let Some((key, value)) = comment_header_pair(comment) else {
            continue;
        };
        let normalized_key = normalize_header_key(key);
        if !is_slicer_variable(key, &normalized_key, value) {
            continue;
        }
        apply_known_header(&mut facts, &normalized_key, value);
    }
    facts
}

fn fill_missing(target: &mut GcodeFacts, source: GcodeFacts) {
    target.slicer = target.slicer.take().or(source.slicer);
    target.filament.material = target.filament.material.take().or(source.filament.material);
    target.filament.profile_name = target
        .filament
        .profile_name
        .take()
        .or(source.filament.profile_name);
    target.filament.length_mm = target.filament.length_mm.or(source.filament.length_mm);
    target.filament.weight_g = target.filament.weight_g.or(source.filament.weight_g);
    target.filament.diameter_mm = target.filament.diameter_mm.or(source.filament.diameter_mm);
    target.filament.density_g_cm3 = target
        .filament
        .density_g_cm3
        .or(source.filament.density_g_cm3);
    target.print.estimated_seconds = target
        .print
        .estimated_seconds
        .or(source.print.estimated_seconds);
    target.print.layer_height_mm = target
        .print
        .layer_height_mm
        .or(source.print.layer_height_mm);
    target.print.total_layers = target.print.total_layers.or(source.print.total_layers);
    target.print.max_z_height_mm = target
        .print
        .max_z_height_mm
        .or(source.print.max_z_height_mm);
    target.print.nozzle_temperature_c = target
        .print
        .nozzle_temperature_c
        .or(source.print.nozzle_temperature_c);
    target.print.bed_temperature_c = target
        .print
        .bed_temperature_c
        .or(source.print.bed_temperature_c);
}

fn thumbnail_starts(comment: &str) -> bool {
    comment.starts_with("thumbnail begin ") || comment.eq_ignore_ascii_case("thumbnail_block_start")
}

fn thumbnail_ends(comment: &str) -> bool {
    comment.eq_ignore_ascii_case("thumbnail end")
        || comment.eq_ignore_ascii_case("thumbnail_block_end")
}

fn comment_header_pair(comment: &str) -> Option<(&str, &str)> {
    let separator = comment.find([':', '='])?;
    let (key, value) = comment.split_at(separator);
    Some((key.trim(), value[1..].trim()))
}

fn normalize_header_key(key: &str) -> String {
    let mut normalized = String::with_capacity(key.len());
    let mut previous_was_separator = true;
    for character in key.chars() {
        if character.is_ascii_alphanumeric() {
            normalized.push(character.to_ascii_lowercase());
            previous_was_separator = false;
        } else if !previous_was_separator {
            normalized.push('_');
            previous_was_separator = true;
        }
    }
    normalized.trim_matches('_').to_owned()
}

fn is_slicer_variable(key: &str, normalized_key: &str, value: &str) -> bool {
    let key_length = normalized_key.chars().count();
    !normalized_key.is_empty()
        && key_length <= VARIABLE_KEY_LIMIT
        && key.chars().any(|character| character.is_ascii_alphabetic())
        && key.chars().all(is_variable_key_character)
        && value.chars().all(|character| !character.is_control())
        && longest_unbroken_value(value) <= UNBROKEN_VALUE_LIMIT
}

fn is_variable_key_character(character: char) -> bool {
    character.is_ascii_alphanumeric()
        || character.is_ascii_whitespace()
        || matches!(character, '_' | '-' | '[' | ']' | '(' | ')' | '.' | '/')
}

fn longest_unbroken_value(value: &str) -> usize {
    value
        .split_whitespace()
        .map(str::len)
        .max()
        .unwrap_or_default()
}

fn push_raw_header(facts: &mut GcodeFacts, key: &str, value: &str) {
    if facts.raw_headers.len() >= RAW_HEADER_LIMIT {
        return;
    }
    facts.raw_headers.push(GcodeHeader {
        key: key.to_owned(),
        value: bounded_header_value(value),
    });
}

#[derive(Clone, Copy)]
enum HeaderField {
    Slicer,
    Material,
    FilamentProfile,
    LengthMm,
    LengthM,
    WeightG,
    DiameterMm,
    Density,
    LayerHeightMm,
    LayerCount,
    MaxHeightMm,
    NozzleC,
    BedC,
    DurationS,
}

/// Semantic aliases, not fuzzy string similarity. Add a fixture with every rule.
/// Unknown variables remain local until their meaning and units are established.
const HEADER_RULES: &[(&[&str], HeaderField)] = &[
    (&["slicer"], HeaderField::Slicer),
    (&["filament_type", "material"], HeaderField::Material),
    (
        &["filament_name", "filament_settings_id"],
        HeaderField::FilamentProfile,
    ),
    (
        &["filament_used_mm", "filament_length", "filament_total_mm"],
        HeaderField::LengthMm,
    ),
    (&["filament_used_m"], HeaderField::LengthM),
    (
        &["filament_used_g", "filament_weight", "filament_weight_g"],
        HeaderField::WeightG,
    ),
    (&["filament_diameter"], HeaderField::DiameterMm),
    (&["filament_density"], HeaderField::Density),
    (&["layer_height"], HeaderField::LayerHeightMm),
    (
        &[
            "total_layer_number",
            "total_layers",
            "total_layers_count",
            "layer_count",
        ],
        HeaderField::LayerCount,
    ),
    (&["max_z_height", "max_height"], HeaderField::MaxHeightMm),
    (
        &["nozzle_temperature", "extruder_temperature", "temperature"],
        HeaderField::NozzleC,
    ),
    (&["bed_temperature"], HeaderField::BedC),
    (
        &[
            "time",
            "estimated_time",
            "estimated_printing_time",
            "estimated_printing_time_normal_mode",
        ],
        HeaderField::DurationS,
    ),
];

fn apply_known_header(facts: &mut GcodeFacts, key: &str, value: &str) {
    let Some((_, field)) = HEADER_RULES
        .iter()
        .find(|(aliases, _)| aliases.contains(&key))
    else {
        return;
    };
    match field {
        HeaderField::Slicer => set_first_text(&mut facts.slicer, value),
        HeaderField::Material => set_first_text(&mut facts.filament.material, value),
        HeaderField::FilamentProfile => set_first_text(&mut facts.filament.profile_name, value),
        HeaderField::LengthM => set_first_number(
            &mut facts.filament.length_mm,
            parse_quantity(value, &[("", 1000.0), ("m", 1000.0)]),
        ),
        HeaderField::LengthMm => {
            set_first_number(&mut facts.filament.length_mm, parse_length_mm(value))
        }
        HeaderField::WeightG => set_first_number(
            &mut facts.filament.weight_g,
            parse_quantity(value, &[("", 1.0), ("g", 1.0)]),
        ),
        HeaderField::DiameterMm => {
            set_first_number(&mut facts.filament.diameter_mm, parse_finite_number(value))
        }
        HeaderField::Density => set_first_number(
            &mut facts.filament.density_g_cm3,
            parse_finite_number(value),
        ),
        HeaderField::LayerHeightMm => {
            set_first_number(&mut facts.print.layer_height_mm, parse_finite_number(value))
        }
        HeaderField::LayerCount => {
            set_first_number(&mut facts.print.total_layers, parse_nonnegative_u32(value))
        }
        HeaderField::MaxHeightMm => {
            set_first_number(&mut facts.print.max_z_height_mm, parse_finite_number(value))
        }
        HeaderField::NozzleC => set_first_number(
            &mut facts.print.nozzle_temperature_c,
            parse_finite_number(value),
        ),
        HeaderField::BedC => set_first_number(
            &mut facts.print.bed_temperature_c,
            parse_finite_number(value),
        ),
        HeaderField::DurationS => {
            set_first_number(&mut facts.print.estimated_seconds, parse_seconds(value))
        }
    }
}

fn set_first_text(slot: &mut Option<String>, value: &str) {
    if slot.is_none() {
        *slot = Some(bounded_header_value(value));
    }
}

fn set_first_number<T>(slot: &mut Option<T>, value: Option<T>) {
    if slot.is_none() {
        *slot = value;
    }
}

fn parse_finite_number(value: &str) -> Option<f64> {
    // A list is not a scalar: never silently keep the first tool/material.
    value
        .trim()
        .parse::<f64>()
        .ok()
        .filter(|number| number.is_finite() && *number >= 0.0)
}

fn parse_quantity(value: &str, units: &[(&str, f64)]) -> Option<f64> {
    let value = value.trim();
    for (unit, factor) in units {
        let Some(number) = value.strip_suffix(unit).and_then(parse_finite_number) else {
            continue;
        };
        let converted = number * factor;
        if converted.is_finite() {
            return Some(converted);
        }
    }
    None
}

fn parse_length_mm(value: &str) -> Option<f64> {
    parse_quantity(
        value,
        &[("", 1.0), ("mm", 1.0), ("cm", 10.0), ("m", 1000.0)],
    )
}

fn parse_nonnegative_u32(value: &str) -> Option<u32> {
    let number = parse_finite_number(value)?;
    (number.fract() == 0.0 && number <= u32::MAX as f64).then_some(number as u32)
}

fn parse_seconds(value: &str) -> Option<f64> {
    if let Some(seconds) = parse_quantity(value, &[("", 1.0), ("s", 1.0)]) {
        return Some(seconds);
    }
    let mut total = 0.0;
    let mut parsed = false;
    for part in value.split_whitespace() {
        let (number, factor) = if let Some(number) = part.strip_suffix('h') {
            (number, 3600.0)
        } else if let Some(number) = part.strip_suffix('m') {
            (number, 60.0)
        } else {
            (part.strip_suffix('s')?, 1.0)
        };
        total += parse_finite_number(number)? * factor;
        parsed = true;
    }
    (parsed && total.is_finite()).then_some(total)
}

fn bounded_header_value(value: &str) -> String {
    let mut characters = value
        .trim()
        .chars()
        .filter(|character| !character.is_control());
    let mut bounded = characters
        .by_ref()
        .take(HEADER_VALUE_LIMIT)
        .collect::<String>();
    if characters.next().is_some() {
        bounded.push('…');
    }
    bounded
}
